package kira.core

/**
 * Сила компьютерного соперника. Какой зверь её показывает — дело интерфейса.
 */
enum class Difficulty {
    /** Ходит почти наугад и регулярно проигрывает. Уровень для самых маленьких. */
    EASY,

    /** Забирает выигрыш и блокирует очевидную угрозу, но вилок не строит. */
    MEDIUM,

    /** Идеальная игра (минимакс). Проиграть такому сопернику нельзя. */
    HARD,
}

/** Режим игры. */
enum class GameMode {
    /** Двое на одном телефоне: Кира против мамы или папы. */
    TWO_PLAYERS,

    /** Кира против компьютера. */
    VERSUS_AI,
}
