package kira.core

/**
 * Сторона в партии. Имён персонажей ядро не знает намеренно:
 * кто именно ходит — Кира, мама, папа или лиса — решает интерфейс.
 */
enum class Side {
    /** Ходит первой. В игре это всегда Кира. */
    FIRST,

    /** Ходит второй: соперник — человек или компьютер. */
    SECOND;

    val opponent: Side
        get() = if (this == FIRST) SECOND else FIRST
}
