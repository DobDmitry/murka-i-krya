package murka.core

/** Уровень соперника-ИИ. Подпись и картинка живут в UI, здесь — только смысл. */
enum class Difficulty {
    /** Котёнок — ходит почти наугад и регулярно проигрывает. Уровень по умолчанию. */
    KITTEN,

    /** Кот — забирает выигрыш и блокирует очевидную угрозу, но вилок не строит. */
    CAT,

    /** Лев — идеальная игра (минимакс). Проиграть ему нельзя. */
    LION,
}

/** Режим игры. */
enum class GameMode {
    /** Двое на одном телефоне. */
    TWO_PLAYERS,

    /** Ребёнок (Мурка) против ИИ (Кря). */
    VERSUS_AI,
}
